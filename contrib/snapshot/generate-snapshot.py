"""Generate src/btgs/snapshot_data.h from the carry-over lists made by btgs_snapshot_extract.py.

Usage:
    python3 contrib/snapshot/generate-snapshot.py [--main main.csv] [--test test.csv] > src/btgs/snapshot_data.h

CSV lines:  new_address,amount_sats,hash160,old_addresses   (lines starting with # are ignored)
Without a file a network gets an empty list. The fingerprints printed at the end (on stderr) must be
copied into src/btgs/snapshot.cpp (EXPECTED_MAIN / EXPECTED_TEST): the node refuses to start if the
built-in list does not match its fingerprint."""
import argparse, hashlib, sys

# Regtest test list (only used with -btgssnapshottest): the first three test framework keys
REGTEST_TEST = [
    ("54d1e6a1b3850bbad70f3fa541e67547d5e6ded0", 1),               # tEf6G5Lz6MGKwBhkgJ9RC9iEFWjuSapVFY
    ("8708dff2bf8b31363cb4201d179b4714aa7b54a0", 100000000000),    # tKEbuKXhbYDw6FjDSQv6ApQ4TWMXHng3kX
    ("d1e414e99c4cf3160d099aeb70438a3ca92dad1a", 25050000000),     # tS4QWH45rjTBExLHs9VVEXdmgkSvzJVsxr
]
MAX_MONEY = 30_000_000 * 100_000_000

def read_csv(path):
    rows = {}
    if not path:
        return []
    for n, line in enumerate(open(path), 1):
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        parts = line.split(",")
        key, sats = parts[2].lower(), int(parts[1])
        if len(key) != 40 or int(key, 16) < 0:
            sys.exit(f"{path}:{n}: bad hash160")
        if sats <= 0:
            sys.exit(f"{path}:{n}: bad amount")
        if key in rows:
            sys.exit(f"{path}:{n}: duplicate key {key}")
        rows[key] = sats
    out = sorted(rows.items())
    if sum(s for _, s in out) > MAX_MONEY:
        sys.exit(f"{path}: total is above the maximum supply")
    return out

def fingerprint(rows):
    """Same as btgs::GetSnapshotHash: double SHA-256 of the serialized vector of P2PKH outputs"""
    def compact(n):
        return bytes([n]) if n < 253 else b"\xfd" + n.to_bytes(2, "little") if n <= 0xffff else b"\xfe" + n.to_bytes(4, "little")
    ser = compact(len(rows))
    for key, sats in rows:
        ser += sats.to_bytes(8, "little") + b"\x19\x76\xa9\x14" + bytes.fromhex(key) + b"\x88\xac"
    return hashlib.sha256(hashlib.sha256(ser).digest()).digest()[::-1].hex()

def emit(name, rows, comment):
    print(f"/** {comment}: {len(rows)} outputs, {sum(s for _, s in rows)} satoshis */")
    print(f"static const std::vector<std::pair<const char*, int64_t>> {name}{{")
    for key, sats in rows:
        print(f'    {{"{key}", {sats}}},')
    print("};\n")

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--main", default="")
    ap.add_argument("--test", default="")
    a = ap.parse_args()
    main_rows, test_rows = read_csv(a.main), read_csv(a.test)
    print("// Generated by contrib/snapshot/generate-snapshot.py - do not edit by hand.")
    print("// Balances carried over from the old BTGS chain: hash160 of the key (hex) and amount in satoshis, sorted by hash160.")
    print("#ifndef BTGS_SNAPSHOT_DATA_H\n#define BTGS_SNAPSHOT_DATA_H\n")
    print("#include <cstdint>\n#include <utility>\n#include <vector>\n")
    print("namespace btgs {")
    emit("SNAPSHOT_MAIN", main_rows, "Mainnet")
    emit("SNAPSHOT_TEST", test_rows, "Testnet")
    emit("SNAPSHOT_REGTEST_TEST", sorted(REGTEST_TEST), "Regtest test list (-btgssnapshottest)")
    print("} // namespace btgs\n\n#endif // BTGS_SNAPSHOT_DATA_H")
    for name, rows in (("EXPECTED_MAIN", main_rows), ("EXPECTED_TEST", test_rows), ("regtest test list", sorted(REGTEST_TEST))):
        print(f"{name}: {fingerprint(rows)}  ({len(rows)} outputs, {sum(s for _, s in rows)} satoshis)", file=sys.stderr)

if __name__ == "__main__":
    main()
